function morningTips(ctx: OpenTipContext): string[] {
  if (ctx.hour >= 5 && ctx.hour < 11) {
    return [
      '早安，先看一眼今天要推进的事。',
      '新的早上，给自己一个清晰起点。',
      '早一点对齐计划，整天都会更稳。',
      '晨光正好，适合确认今日重点。',
    ]
  }
  return []
}

function eveningTips(ctx: OpenTipContext): string[] {
  if (ctx.hour >= 18 || ctx.hour < 5) {
    return [
      '晚上好，收一收今天的进度吧。',
      '夜色下来了，看看还有什么想记上。',
      '睡前看一眼安排，心里更踏实。',
      '今天辛苦了，剩下的事可以明天再来。',
    ]
  }
  return []
}

function weekdayTips(ctx: OpenTipContext): string[] {
  if (ctx.weekday === 0 || ctx.weekday === 6) {
    return [
      '周末也适合轻量安排，别排太满。',
      '休息日也可以有一点温柔计划。',
      '周末好时光，留给重要的人和事。',
    ]
  }
  if (ctx.weekday === 1) {
    return ['周一开工，先抓住最重要的一件。', '新的一周，从清晰的安排开始。']
  }
  if (ctx.weekday === 5) {
    return ['周五啦，收尾一件事也很有成就感。', '临近周末，把该推进的推进一下。']
  }
  return []
}

function statusTips(ctx: OpenTipContext): string[] {
  const tips: string[] = []
  if (ctx.total === 0) {
    tips.push(
      '还空着，记一件小事到时间轴上吧。',
      '从一件想做的事开始，就够了。',
      '空白也没关系，随时可以写上第一笔。',
    )
  }
  if (ctx.overdue > 0) {
    tips.push(
      `有 ${ctx.overdue} 件已逾期，轻轻看一眼就好。`,
      '逾期的事不用慌，选一件先处理。',
      '把过期的安排理一理，肩膀会轻松些。',
    )
  }
  if (ctx.inFlight > 0) {
    tips.push(
      `正有 ${ctx.inFlight} 件在推进，今天继续一点点。`,
      '进行中的事还在路上，你已经在动了。',
      '看见进度条，就知道没有白忙。',
    )
  }
  if (ctx.upcoming > 0) {
    tips.push(
      `还有 ${ctx.upcoming} 件待开始，来日方长。`,
      '待办在后面排着，先把眼前做好。',
      '未来的安排已经就位，挺安心的。',
    )
  }
  if (ctx.completed > 0 && ctx.overdue === 0) {
    tips.push(
      `已完成 ${ctx.completed} 件，状态不错。`,
      '完成过的事会给你底气。',
      '好看的进度，是一点点攒出来的。',
    )
  }
  return tips
}

export function readRecentOpenTips(): string[] {
  try {
    const raw = localStorage.getItem(STORAGE_KEY)
    if (!raw) return []
    const parsed = JSON.parse(raw) as unknown
    if (!Array.isArray(parsed)) return []
    return parsed.filter((item): item is string => typeof item === 'string')
  } catch {
    return []
  }
}

export function writeRecentOpenTip(tip: string, recent = readRecentOpenTips()) {
  const next = [tip, ...recent.filter((item) => item !== tip)].slice(0, RECENT_LIMIT)
  try {
    localStorage.setItem(STORAGE_KEY, JSON.stringify(next))
  } catch {
    // ignore quota / private mode
  }
  return next
}

function pickFrom(pool: string[], recent: string[], random = Math.random): string | null {
  const fresh = pool.filter((tip) => !recent.includes(tip))
  const source = fresh.length > 0 ? fresh : pool
  if (source.length === 0) return null
  return source[Math.floor(random() * source.length)] ?? null
}

/** Prefer contextual tips, fall back to flavor tips; avoid recent repeats. */
export function pickOpenTip(
  ctx: OpenTipContext,
  recent = readRecentOpenTips(),
  random = Math.random,
): string {
  const contextual = [
    ...statusTips(ctx),
    ...morningTips(ctx),
    ...eveningTips(ctx),
    ...weekdayTips(ctx),
  ]

  // 70% chance contextual when available, else flavor — keeps status useful but not repetitive.
  const preferContextual = contextual.length > 0 && random() < 0.7
  const primary = preferContextual ? contextual : FLAVOR_TIPS
  const secondary = preferContextual ? FLAVOR_TIPS : contextual

  return (
    pickFrom(primary, recent, random) ??
    pickFrom(secondary, recent, random) ??
    FLAVOR_TIPS[0]!
  )
}

export function buildOpenTipContext(
  summary: {
    overdue: number
    inFlight: number
    upcoming: number
    completed: number
    total: number
  },
  now = new Date(),
): OpenTipContext {
  return {
    overdue: summary.overdue,
    inFlight: summary.inFlight,
    upcoming: summary.upcoming,
    completed: summary.completed,
    total: summary.total,
    hour: now.getHours(),
    weekday: now.getDay(),
  }
}

